// Builds ortak/gicons-data.js from the game-icons.net set (CC BY 3.0, via the @iconify-json/game-icons package)
// and scripts/gicons-map.json (emoji → [icon name, palette]). Only the icons in the map are embedded.
// Usage: node scripts/make-gicons.js <path to @iconify-json/game-icons/icons.json>
const fs = require('fs'), path = require('path');
const src = process.argv[2];
if (!src) { console.error('usage: node scripts/make-gicons.js <icons.json>'); process.exit(1); }
const set = JSON.parse(fs.readFileSync(src, 'utf8'));
const map = JSON.parse(fs.readFileSync(path.join(__dirname, 'gicons-map.json'), 'utf8'));
const paths = {};
for (const [, [name]] of Object.entries(map)) {
  const ic = set.icons[name] || (set.aliases && set.aliases[name] && set.icons[set.aliases[name].parent]);
  if (!ic) throw new Error('missing icon ' + name);
  paths[name] = ic.body.replace(/\s*fill="currentColor"/g, '');
}
const out = '// Generated by scripts/make-gicons.js — game-icons.net (CC BY 3.0: Lorc, Delapouite and contributors). Do not edit.\n' +
  'window.GI_DATA = ' + JSON.stringify({ paths, map }) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'ortak', 'gicons-data.js'), out);
console.log(Object.keys(paths).length + ' icons, ' + Math.round(out.length / 1024) + ' KB');
